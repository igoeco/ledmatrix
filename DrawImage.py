def spos(x, y):  # for a serpentine raster
    if x & 0x1:  # is X odd
        pos = x * 16 + (16 - 1 - y)
    else:  # x is even
        pos = x * 16 + y
    return 255-pos

def DrawPixel(x, y, r=None,g=None,b=None):
    if r is None:
        r = randint(0, 60)
    if g is None:
        g = randint(0, 60)
    if b is None:
        b = randint(0, 60)
    np[spos(x, y)] = (r, g, b)

def DrawBitmap(image, x=0, y=0, w=16, h=16):
    for i in range (0, w):
        for j in range (0, h):
            r = (image[j*16+i] & 0x1F)
            g = ((image[j*16+i] & 0x3E0)>> 5)
            b = ((image[j*16+i] & 0xF800)>> 11)
            DrawPixel(x+i,y+j,r,g,b)

